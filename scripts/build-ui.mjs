import './build-icons.mjs';
import { build, transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const license = await readFile('node_modules/marked/LICENSE', 'utf8');
const markedNotice = '/* Bundled marked 18.1.0 license:\n' + license.replaceAll('*/', '* /') + '\n*/';
const options = { write: false, bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true };
async function emit(file, output) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== output) throw new Error(file + ' is stale; run npm run build:ui');
  } else await writeFile(file, output);
}

// Keep the standalone renderer for source-level tests and existing asset URLs.
const markdown = await build({ ...options, entryPoints: ['src/markdown.ts'], outfile: 'public/markdown.js', banner: { js: markedNotice } });
await emit('public/markdown.js', markdown.outputFiles[0].text);

// app.js and its small modules remain editable source; only this generated
// entry is loaded by index.html. No runtime imports or extra requests remain.
const app = await build({ ...options, entryPoints: ['public/app.js'], outfile: 'public/app.bundle.js',
  banner: { js: '/* Generated by npm run build:ui from public/app.js. Do not edit. */\n' + markedNotice } });
await emit('public/app.bundle.js', app.outputFiles[0].text);

const css = await transform(await readFile('src/browser/style.css', 'utf8'), { loader: 'css', target: 'es2022', minify: true,
  banner: '/* Generated by npm run build:ui from src/browser/style.css. Do not edit. */' });
await emit('public/style.css', css.code);
