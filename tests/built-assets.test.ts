import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';

test('shipped chat loads one self-contained module and the generated stylesheet', async () => {
  const dom = new JSDOM(await readFile('public/index.html', 'utf8'));
  try {
    const document = dom.window.document;
    assert.deepEqual([...document.querySelectorAll('script')].map(node => [node.type, node.getAttribute('src')]), [['module', '/app.bundle.js']]);
    assert.deepEqual([...document.querySelectorAll('link[rel=stylesheet]')].map(node => node.getAttribute('href')), ['/style.css']);
  } finally { dom.window.close(); }
  // Parse the emitted file, so an accidental static/dynamic runtime import
  // cannot pass by inspecting only the source entry or its build options.
  const parsed = await build({ entryPoints: ['public/app.bundle.js'], write: false, metafile: true, format: 'esm', logLevel: 'silent' });
  for (const output of Object.values(parsed.metafile!.outputs)) assert.deepEqual(output.imports, []);
  assert.doesNotMatch(await readFile('public/app.bundle.js', 'utf8'), /\bimport\s*\(/, 'the emitted entry must not defer imports to runtime');
  const css = await readFile('public/style.css', 'utf8');
  assert.match(css, /Generated by npm run build:ui from src\/browser\/style.css/);
  assert.ok(css.length < (await readFile('src/browser/style.css', 'utf8')).length);
});

test('generated entry retains complete marked and Lucide license notices', async () => {
  const marked = (await readFile('node_modules/marked/LICENSE', 'utf8')).replaceAll('*/', '* /');
  for (const file of ['public/app.bundle.js', 'public/markdown.js'])
    assert.ok((await readFile(file, 'utf8')).includes(marked), file + ' must retain the complete marked license');
  assert.match(await readFile('public/index.html', 'utf8'), /Lucide 1\.57\.0; Copyright/);
  assert.equal(await readFile('public/lucide-license.txt', 'utf8'), await readFile('vendor/lucide/LICENSE', 'utf8'));
});
